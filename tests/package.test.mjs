test('main skill instructions must stay below 500 lines', async t => {
  const root = await fixture(t);
  const file = path.join(root, 'skills', FIRST, 'SKILL.md');
  const content = skillText(FIRST).trimEnd();
  const lines = content.split('\n').length;
  await writeFile(file, `${content}\n${'More instructions.\n'.repeat(499 - lines)}`);
  assert.deepEqual(await validateRepository(root), []);
  await writeFile(file, `${content}\n${'More instructions.\n'.repeat(500 - lines)}`);
  assert.match((await validateRepository(root)).join('\n'), /fewer than 500 lines/);
});

test('validator checks missing inline links, images, and reference definitions', async t => {
  const root = await fixture(t);
  const file = path.join(root, 'skills', FIRST, 'SKILL.md');
  await writeFile(file, `${skillText(FIRST)}\n[Missing](references/missing.md)\n![Image](assets/missing.png)\n[ref]: assets/missing.json\n[Encoded](assets/%ZZ)\n`);
  const errors = (await validateRepository(root)).join('\n');
  for (const missing of ['references/missing.md', 'assets/missing.png', 'assets/missing.json']) {
    assert.ok(errors.includes(`missing local Markdown target: ${missing}`));
  }
  assert.match(errors, /invalid URL encoding/);
});

test('validator rejects links outside an individual skill, including encoded traversal', async t => {
  const root = await fixture(t);
  const file = path.join(root, 'skills', FIRST, 'SKILL.md');
  await writeFile(file, `${skillText(FIRST)}\n[Other](../${REQUIRED_SKILLS[1]}/SKILL.md)\n[Encoded](%2e%2e/${REQUIRED_SKILLS[1]}/SKILL.md)\n[Absolute](/tmp/credential)\n[File](file:///tmp/credential)\n[Windows](C:/credential)\n[Web](https://example.com/)\n[Mail](mailto:example@example.com)\n[Anchor](#instructions)\n`);
  const errors = await validateRepository(root);
  assert.equal(errors.filter(error => error.includes('leaves the individual skill')).length, 3);
  assert.equal(errors.filter(error => error.includes('must be relative')).length, 2);
  assert.equal(errors.length, 5);
});

test('validator rejects symbolic links instead of following them', async t => {
  const root = await fixture(t);
  const directory = path.join(root, 'skills', FIRST);
  const outside = await temporaryDirectory(t);
  await writeFile(path.join(outside, 'outside.md'), '# Outside\n');
  await symlink(outside, path.join(directory, 'linked'), 'dir');
  await writeFile(path.join(directory, 'SKILL.md'), `${skillText(FIRST)}\n[Linked](linked/outside.md)\n`);
  const errors = (await validateRepository(root)).join('\n');
  assert.match(errors, /only regular files and directories/);
  assert.match(errors, /local Markdown link points to a symbolic link/);
});

test('secret checks reject narrow token formats and literal credentials without printing values', async t => {
  const root = await fixture(t);
  const directory = path.join(root, 'skills', FIRST);
  const token = `ghp_${'a'.repeat(36)}`;
  await writeFile(path.join(directory, 'assets.md'), `${token}\n-----BEGIN ${'RSA '}PRIVATE KEY-----\nAKIA${'A'.repeat(16)}\napi_key = "${'aB3'.repeat(12)}"\n`);
  await writeFile(path.join(directory, '.env'), 'EXAMPLE=value\n');
  const errors = (await validateRepository(root)).join('\n');
  for (const label of ['GitHub token', 'private key', 'AWS access key', 'literal credential', 'credential files']) {
    assert.ok(errors.includes(label), label);
  }
  assert.ok(!errors.includes(token));
});

