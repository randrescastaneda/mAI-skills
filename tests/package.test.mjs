test('secret checks recognize literal hexadecimal APIM keys', async t => {
  const root = await fixture(t);
  const directory = path.join(root, 'skills', FIRST);
  const key = '0123456789abcdef'.repeat(2);
  await writeFile(path.join(directory, 'example.py'), `APIM_SUBSCRIPTION_KEY = "${key}"\n`);
  const errors = await validateRepository(root);
  assert.equal(errors.length, 1);
  assert.match(errors[0], /possible literal credential/);
  assert.ok(!errors[0].includes(key));
});

test('known credential filenames are rejected without reading their contents', async t => {
  const root = await fixture(t);
  const file = path.join(root, 'skills', FIRST, 'credentials.json');
  await writeFile(file, `{"token":"ghp_${'a'.repeat(36)}"}`);
  await chmod(file, 0o000);
  const errors = await validateRepository(root);
  assert.equal(errors.length, 1);
  assert.match(errors[0], /credential files must not be distributed/);
});
