test('npm tarball contains only distribution files and all nine complete skills', async t => {
  const cache = await temporaryDirectory(t);
  const result = spawnSync('npm', ['pack', '--dry-run', '--json', '--ignore-scripts'], {
    cwd: ROOT,
    encoding: 'utf8',
    timeout: 30_000,
    env: { ...process.env, npm_config_cache: cache, npm_config_update_notifier: 'false' },
  });
  assert.equal(result.error, undefined);
  assert.equal(result.status, 0, result.stderr);
  const [tarball] = JSON.parse(result.stdout);
  assert.equal(tarball.name, '@randrescastaneda/mai-skills');
  const files = tarball.files.map(file => file.path);
  assert.ok(files.includes('package.json'));
  assert.ok(files.includes('README.md'));
  for (const name of REQUIRED_SKILLS) {
    assert.ok(files.includes(`skills/${name}/SKILL.md`), `Missing packaged skill: ${name}`);
  }
  for (const file of files) {
    assert.ok(['package.json', 'README.md', 'SOURCES.md'].includes(file)
      || REQUIRED_SKILLS.some(name => file.startsWith(`skills/${name}/`)), `Unexpected package file: ${file}`);
    assert.ok(!/(?:^|\/)__pycache__\//.test(file) && !/\.py[co]$/.test(file),
      `Generated bytecode in package: ${file}`);
  }
  for (const name of REQUIRED_SKILLS) {
    async function check(directory) {
      for (const entry of await readdir(directory, { withFileTypes: true })) {
        if (entry.name === '__pycache__' || /\.py[co]$/.test(entry.name)) continue;
        const file = path.join(directory, entry.name);
        if (entry.isDirectory()) await check(file);
        else assert.ok(files.includes(path.relative(ROOT, file).split(path.sep).join('/')),
          `Skill resource omitted from package: ${path.relative(ROOT, file)}`);
      }
    }
    await check(path.join(ROOT, 'skills', name));
  }
});

test('package exclusions keep generated bytecode out even when present locally', async t => {
  const root = await fixture(t);
  await writeFile(path.join(root, 'package.json'), await readFile(path.join(ROOT, 'package.json')));
  const directory = path.join(root, 'skills', FIRST);
  await mkdir(path.join(directory, '__pycache__'));
  await writeFile(path.join(directory, '__pycache__', 'example.cpython-312.pyc'), 'generated');
  await writeFile(path.join(directory, 'example.pyc'), 'generated');
  await writeFile(path.join(directory, 'example.pyo'), 'generated');
  const result = spawnSync('npm', ['pack', '--dry-run', '--json', '--ignore-scripts'], {
    cwd: root,
    encoding: 'utf8',
    timeout: 30_000,
    env: { ...process.env, npm_config_cache: await temporaryDirectory(t), npm_config_update_notifier: 'false' },
  });
  assert.equal(result.error, undefined);
  assert.equal(result.status, 0, result.stderr);
  const [tarball] = JSON.parse(result.stdout);
  assert.equal(tarball.files.length, 11);
  assert.ok(tarball.files.every(file => file.path.endsWith('SKILL.md')
    || ['package.json', 'README.md'].includes(file.path)));
});

